# -*- coding: utf-8 -*-
"""
config.py — 运行时配置（.env 文件 + 环境变量，多实例可通过 CIDAREN_ENV_FILE 隔离）
继承 LangQi99/cidaren 的配置管理，并扩展 AI 策略 / 答题节奏 / 重刷轮数等选项。
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
LOG_PATH = BASE_DIR / "run.log"


def log(msg: str, end: str = "\n"):
    """输出到控制台 + 写日志文件。"""
    ts = time.strftime("%Y-%m-%d %H:%M:%S")
    line = f"[{ts}] {msg}"
    print(line, end=end, flush=True)
    try:
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line + end)
    except Exception:
        pass


def _resolve_env_file(path=None) -> Path:
    if not path:
        path = ".env"
    p = Path(path)
    return p if p.is_absolute() else (BASE_DIR / p)


ENV_FILE = _resolve_env_file(os.environ.get("CIDAREN_ENV_FILE"))


def set_env_file(path: str) -> Path:
    global ENV_FILE
    ENV_FILE = _resolve_env_file(path)
    return ENV_FILE


# 可配置字段全集
CONFIG_FIELDS = [
    # 词达人鉴权（LangQi99/cidaren 方案）
    "USERTOKEN", "ABC", "AUTH_V",
    # 自学任务
    "COURSE_ID", "STUDY_GRADE",
    # LLM（OpenAI 兼容）
    "LLM_URL", "LLM_KEY", "LLM_MODEL", "LLM_MAX_TOKENS",
    # AI 策略：on = AI 优先答题（Cidaren-AI 思路）；off = 规则优先、LLM 兜底（LangQi99 思路）
    "AI_PRIORITY",
    # 答题节奏与重刷（Cidaren-AI 思路）
    "DELAY_PER_QUESTION", "MAX_ROUNDS",
    # 防卡保护：单题超时秒数；USE_WORD_API=0 时禁用查词接口（弱网提速）
    "QUESTION_TIMEOUT", "USE_WORD_API",
    # OCR 读图：off=关闭；llm=大模型视觉；tesseract=本地OCR；baidu=百度OCR
    "OCR_MODE", "BAIDU_OCR_AK", "BAIDU_OCR_SK",
]

DEFAULT_CONFIG = {
    "USERTOKEN": "",
    "ABC": "",
    "AUTH_V": "",
    "COURSE_ID": "CET4_v2",
    "STUDY_GRADE": "2",
    "LLM_URL": "",
    "LLM_KEY": "",
    "LLM_MODEL": "deepseek-chat",
    "LLM_MAX_TOKENS": "1024",
    "AI_PRIORITY": "1",
    "DELAY_PER_QUESTION": "2",
    "MAX_ROUNDS": "10",
    "QUESTION_TIMEOUT": "60",
    "USE_WORD_API": "1",
    "OCR_MODE": "off",
    "BAIDU_OCR_AK": "",
    "BAIDU_OCR_SK": "",
}

REQUIRED_AUTH_FIELDS = ("USERTOKEN",)


def _parse_env_value(raw: str) -> str:
    value = raw.strip()
    if not value:
        return ""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        try:
            return json.loads(value) if value[0] == '"' else value[1:-1]
        except Exception:
            return value[1:-1]
    return value


def _format_env_value(value) -> str:
    if value is None:
        value = ""
    value = str(value)
    if value == "":
        return '""'
    if any(ch.isspace() for ch in value) or any(ch in value for ch in '#"\\'):
        return json.dumps(value, ensure_ascii=False)
    return value


def load_env_file() -> dict:
    if not ENV_FILE.exists():
        return {}
    data = {}
    for raw_line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip().removeprefix("export ").strip()
        if not key:
            continue
        data[key] = _parse_env_value(value)
    return data


def get_runtime_config() -> dict:
    config = dict(DEFAULT_CONFIG)
    config.update(load_env_file())
    for key in CONFIG_FIELDS:
        if key in os.environ:
            config[key] = os.environ[key]
    return config


def save_runtime_config(payload: dict) -> dict:
    current = load_env_file()
    for key in CONFIG_FIELDS:
        if key not in payload:
            continue
        value = payload.get(key, "")
        current[key] = "" if value is None else str(value).strip()
    merged = dict(DEFAULT_CONFIG)
    merged.update(current)

    lines = [
        "# cidaren-ultimate runtime config",
        "# Generated by Web 控制台，按需修改即可。",
        "",
        "# 词达人鉴权",
    ]
    for key in REQUIRED_AUTH_FIELDS:
        lines.append(f"{key}={_format_env_value(merged.get(key, ''))}")
    for key in ("ABC", "AUTH_V"):
        lines.append(f"{key}={_format_env_value(merged.get(key, ''))}")
    lines.extend([
        "",
        "# 自学任务课程",
        f"COURSE_ID={_format_env_value(merged.get('COURSE_ID', ''))}",
        f"STUDY_GRADE={_format_env_value(merged.get('STUDY_GRADE', ''))}",
        "",
        "# LLM (OpenAI 兼容)",
        f"LLM_URL={_format_env_value(merged.get('LLM_URL', ''))}",
        f"LLM_KEY={_format_env_value(merged.get('LLM_KEY', ''))}",
        f"LLM_MODEL={_format_env_value(merged.get('LLM_MODEL', ''))}",
        f"LLM_MAX_TOKENS={_format_env_value(merged.get('LLM_MAX_TOKENS', ''))}",
        "",
        "# AI 策略: 1 = AI 优先, 0 = 规则优先(LLM 兜底)",
        f"AI_PRIORITY={_format_env_value(merged.get('AI_PRIORITY', ''))}",
        "",
        "# 答题节奏(秒)与最大重刷轮数",
        f"DELAY_PER_QUESTION={_format_env_value(merged.get('DELAY_PER_QUESTION', ''))}",
        f"MAX_ROUNDS={_format_env_value(merged.get('MAX_ROUNDS', ''))}",
        "",
        "# 防卡保护: 单题超时(秒); USE_WORD_API=0 禁用查词接口(弱网提速)",
        f"QUESTION_TIMEOUT={_format_env_value(merged.get('QUESTION_TIMEOUT', ''))}",
        f"USE_WORD_API={_format_env_value(merged.get('USE_WORD_API', ''))}",
        "",
        "# OCR 读图: off/llm/tesseract/baidu",
        f"OCR_MODE={_format_env_value(merged.get('OCR_MODE', ''))}",
        f"BAIDU_OCR_AK={_format_env_value(merged.get('BAIDU_OCR_AK', ''))}",
        f"BAIDU_OCR_SK={_format_env_value(merged.get('BAIDU_OCR_SK', ''))}",
        "",
    ])
    ENV_FILE.write_text("\n".join(lines), encoding="utf-8")
    # 配置文件含 USERTOKEN 等敏感凭据，限制为仅所有者可读写
    try:
        os.chmod(ENV_FILE, 0o600)
    except OSError:
        pass  # Windows 等不支持 chmod 的平台忽略
    for key in CONFIG_FIELDS:
        os.environ[key] = merged.get(key, DEFAULT_CONFIG.get(key, ""))
    return merged


def get_missing_auth_fields(config=None) -> list:
    cfg = config or get_runtime_config()
    return [key for key in REQUIRED_AUTH_FIELDS if not (cfg.get(key) or "").strip()]


def build_subprocess_env(config=None) -> dict:
    cfg = config or get_runtime_config()
    env = os.environ.copy()
    for key in CONFIG_FIELDS:
        env[key] = cfg.get(key, DEFAULT_CONFIG.get(key, ""))
    return env


def env_file_path() -> str:
    return str(ENV_FILE)


def as_int(value, default: int) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def as_bool(value, default: bool = True) -> bool:
    if value is None:
        return default
    return str(value).strip().lower() in ("1", "true", "yes", "on")
